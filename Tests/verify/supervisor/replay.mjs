// Replays scenarios on the model and prints the expected observable after every poll.
//   node replay.mjs            human table
//   node replay.mjs --swift    Swift literal used by Tests/ManbokPlatformTests/CaptureSupervisorReplayTests.swift
// Scenario tokens are the same strings the Swift harness parses.
import { init, replayStep, observe } from "./supervisor.model.mjs";
export const scenarios = {
  N1_arrival: ["list:1:1", "poll", "poll"],
  N2_emptyDemandAbandon: ["list:1:1", "poll", "poll", "empty", "poll", "list:1:1", "poll"],
  N3_deviceSwitchHealthy: ["list:1:1", "poll", "poll", "list:1:2", "poll", "poll"],
  N4_stallWatchdog: ["list:1:1", "mode:N", "poll", "poll", "poll", "poll"],
  N5_silenceLadder: ["list:1:1", "mode:S", ...Array(20).fill("poll")],
  N6_signalRestart: ["list:1:1", "poll", "poll", "signal", "poll", "poll"],
  N7_releaseThenStart: ["list:1:1", "poll", "poll", "list:1:0", "poll", "list:1:1", "poll"],
  N8_startFailureBackoff: ["list:1:1", "poll!", "poll!", "poll!", "poll!", "poll!", "poll!", "poll"],
  N9_stop: ["list:1:1", "poll", "poll", "stop"],
  // Break-path replays (a model rule fails on the same steps, see README)
  N10_fourSlowSwitchesStartWithoutDelay: ["list:1:1", "poll",
    "list:1:0", "poll", "poll", "list:1:1", "poll",
    "list:1:0", "poll", "poll", "list:1:1", "poll",
    "list:1:0", "poll", "poll", "list:1:1", "poll",
    "list:1:0", "poll", "list:1:1", "poll", "poll", "poll", "poll"],
  // Chunks flow, mic released, then the next start throws twice and succeeds: the second attempt must not inherit the first release's value.
  M8_flowValueIsConsumedOnce: ["list:1:1", "poll", "poll", "list:1:0", "poll", "list:1:1", "poll!", "poll", "mode:N", ...Array(14).fill("poll")],
  B2_holdThenStartFailure: ["list:1:1", "mode:S", ...Array(19).fill("poll"), "signal", "poll!", "poll"],
  // Mutant-discriminating replays: the rows differ between the base model and the named mutant model
  // (see README, "mutant -> rule -> replay"). Each fails on the real code when the matching fix is removed.
  M1_fastSwitchesKeepBackoffLow: ["list:1:1", ...Array(7).fill(["poll", "list:1:0", "poll", "list:1:1", "poll"]).flat(), "poll"],
  M2_liveSwitchesResetBackoff: ["list:1:1", "poll", ...Array(5).fill(["list:1:2", "poll", "list:1:1", "poll"]).flat(), "poll"],
  M3_freshWorkerGetsGraceBeforeStall: ["list:1:1", "mode:N", "poll", "poll", "poll", "poll"],
  M4_silenceLadderStepsBeforeHold: ["list:1:1", "mode:S", ...Array(24).fill("poll")],
  M5_emptyDemandThenQuickReturn: ["list:1:1", "poll", "poll", "list:1:0", "poll", "empty", "poll", "list:1:1", "poll", "poll", "poll"],
  M6_noDeviceReleasesWorker: ["list:1:1", "poll", "poll", "list:1:0", "poll", "poll"],
  M7_delayIsCapped: ["list:1:1", ...Array(40).fill("poll!"), "poll", "poll"],
  B3_staleBackoffAfterLongFlow: ["list:1:1", "mode:N", "poll", "poll", "poll", "mode:F", ...Array(20).fill("poll"), "mode:N", "poll", "poll", "mode:F", "signal", "poll", "poll"],
};
const out = {};
for (const [name, toks] of Object.entries(scenarios)) {
  let s = init, attempts = 0; const rows = [];
  for (const t of toks) {
    s = replayStep(s, t);
    if (t.startsWith("poll") || t === "stop") { if (s.ev.trig) attempts++; rows.push({ tok: t, attempts, ...observe(s) }); }
  }
  out[name] = { toks, rows };
}
if (process.argv.includes("--json")) {
  console.log(JSON.stringify(Object.fromEntries(Object.entries(out).map(([n, v]) => [n, v.rows.map((r) => [r.capturing, r.target, r.attempts, r.holding, r.deferred].join(","))])), null, 1));
} else if (process.argv.includes("--swift")) {
  const b = (x) => (x ? "true" : "false");
  console.log("// GENERATED by Tests/verify/supervisor/replay.mjs --swift. Do not edit by hand.");
  console.log("enum ReplayExpected {");
  console.log("    typealias Row = (capturing: Bool, target: UInt32, attempts: Int, holding: Bool, deferred: Bool)");
  for (const [name, { toks, rows }] of Object.entries(out)) {
    console.log(`    static let ${name}_steps: [String] = [${toks.map((t) => JSON.stringify(t)).join(", ")}]`);
    console.log(`    static let ${name}: [Row] = [`);
    for (const r of rows) console.log(`        (${b(r.capturing)}, ${r.target}, ${r.attempts}, ${b(r.holding)}, ${b(r.deferred)}),`);
    console.log("    ]");
  }
  console.log("}");
} else {
  for (const [name, { rows }] of Object.entries(out)) {
    console.log(`\n${name}`);
    rows.forEach((r, i) => console.log(`  poll ${i + 1}: capturing=${r.capturing} target=${r.target} attempts=${r.attempts} holding=${r.holding} deferred=${r.deferred} backoffCount=${r.c}`));
  }
}
